import Foundation

/// Промпты и дайджесты двухэтапного Director.
///
/// Раньше один вызов должен был выдать тему, обоснование, план эссе и 16-24 сцены
/// за один раз: ответ вырастал до 21 тысячи символов, обрывался на середине, а
/// оборванный хвост молча засчитывался успехом. Теперь два независимых прохода:
/// этап 1 ищет только темы-кандидаты (короткий ответ, который почти всегда
/// закрывается), этап 2 строит эссе вокруг уже отобранной гейтом темы.
enum DirectorStagedAnalysis {

    /// Сколько символов диалогов видит этап 1. Темы выводятся из лексики фильма,
    /// и для этого хватает стратифицированной выборки — полный монотонный промпт
    /// в 71 тысячу символов как раз и был тем, что ломало ответ.
    static let stage1DigestChars = 18_000
    static let stage1MaxTokens = 1_024
    /// Этап 2 пишет план эссе и пул сцен. 4 096 не хватало: в живом прогоне
    /// модель выдала 40 сцен и упёрлась в потолок (`generatedTokens=4096
    /// cap=4096 stop=length complete=truncated`), то есть контракт в 14-22 сцены
    /// вместе с планом и обоснованием физически длиннее 4 096 токенов.
    static let stage2MaxTokens = 5_120
    /// Резерв для конкретной причины отказа при повторном отборе сцен.
    static let evidenceFeedbackChars = 600
    /// Stage-2 retry includes compact IDs or time ranges from its prior selection.
    static let essaySceneContextChars = 900

    static func catalogueInstructions(movieTitle: String, concept: ThematicConcept) -> String {
        """
        Ти — режисер тематичного кіноесе за фільмом «\(movieTitle)». Мова текстів — українська.
        Вибрана тема: «\(concept.word)». Обрана грань: \(concept.philosophicalPremise.prefix(600)).
        Тему вже обрано: збережи її слово і сенс. Побудуй аргументацію, не переказ сюжету.

        Матеріал — КАТАЛОГ реальних сцен із ID, точними межами й діалогом.
        Обери 14–22 РІЗНІ ID, що найкраще розкривають тему, і побудуй повний план
        з п'яти актів: рівно 1 hook, щонайменше по 3 сцени form, psychology, philosophy
        та catharsis. Признач роль кожній сцені. Розподіли матеріал на есе в межах
        4–8 хвилин; кожна сцена має 18–40 секунд. Якщо план не вкладається, переобери
        сцени та перевір тривалість. Не повторюй аргументи для заповнення актів.
        Якщо повний доказовий план неможливий, поверни помилку у JSON.
        ID бери виключно з каталогу. Таймкоди і цитати не пиши: їх підставить каталог.
        У кожної сцени має бути конкретне пояснення, яку думку акта вона доводить.
        Відкидай фрагменти, що починаються відповіддю без питання або займенником без
        зрозумілого попередника. Завершена репліка ще не означає завершену сцену:
        перевір, чи показано наслідок рішення, а не лише підготовку до нього.
        Кожна наступна сцена має додати аргумент, суперечність або розв'язку —
        повтор тієї самої тези без нового значення та побічний сюжет не є розвитком.
        Хук формулюй конкретним питанням; catharsis має відповісти саме на нього.
        Сам визнач найкращий хук: порівняй формулювання внутрішньо, поверни тільки один.
        Не перекладай режисерський вибір на глядача або користувача програми.
        Якщо тема метафорична, поясни її грань у слогані й назві, щоб не обіцяти іншу тему.
        Ролі: hook — рівно одна сцена-зацікавлення; form — структура/ритм діалогів;
        psychology — мотив і конфлікт героя; philosophy — людська дилема та ціна вибору;
        catharsis — висновок, що завершує тезу. Кожній ролі потрібен матеріал.
        Не приписуй кадру колір, ракурс або реквізит, яких не видно з діалогу.
        Порядок сцен визначає думка, а не хронологія. Найсильніші став на початок пулу.

        Поверни один валідний JSON без markdown. Усі значення тексту — твої формулювання
        з аналізу каталогу; у зразку копіюй тільки структуру. Кожен рядок selection —
        масив РІВНО з 5 значень: ID, роль, вага 0–1, featured true/false, пояснення до 12 слів.
        {
          "primaryConcept":{"word":"\(concept.word)","tagline":"<СЛОГАН>",
            "philosophicalPremise":"<ТЕЗА>","suggestedTitle":"<НАЗВА YOUTUBE>"},
          "essayPlan":{"thesis":"<ЩО ДОВОДИТЬ ЕСЕ>",
            "hook":"<ОДИН НАЙКРАЩИЙ ХУК>",
            "ctaVariants":["<ЗАКЛИК ДО ОБГОВОРЕННЯ В TELEGRAM>"],
            "actFocus":{"form":"<ДУМКА>","psychology":"<ДУМКА>",
              "philosophy":"<ДУМКА>","catharsis":"<ВИСНОВОК>"}},
          "selection":[["<ID З КАТАЛОГУ>","hook",0.9,true,"<ЩО ДОВОДИТЬ СЦЕНА>"]],
          "reasoning":"<ЧОМУ ЦІ СЦЕНИ РАЗОМ РОЗКРИВАЮТЬ ТЕМУ, ДО 300 СИМВОЛІВ>"
        }
        """
    }

    static func cataloguePrompt(movieTitle: String, overview: String, digest: String) -> String {
        """
        Фільм: «\(movieTitle)»
        Синопсис — тільки контекст, не джерело сцен: \(overview)
        КАТАЛОГ (ID, секунди, реальний діалог):
        \"\"\"
        \(digest)
        \"\"\"
        Обери сцени для есе на вже затверджену тему. Тільки JSON за схемою selection.
        """
    }

    /// Ремарка другого заходу этапа 1. Її довжина — частина промпта, який піде в
    /// модель, тому бюджет рахуємо найгіршим заходом: інакше другий захід вилазить
    /// за стелю KV рівно на ті токени, що ми не порахували.
    static let candidatesRetryNote =
        "\n\nУВАГА: попередня відповідь була невалідною або обірваною. Поверни ТІЛЬКИ валідний JSON з п'ятьма кандидатами, без пояснень і без markdown."

    /// Те саме для этапа 2: менший пул сцен — це текстовий суфікс до промпта, який
    /// також їсть KV.
    static let essayRetryNote =
        "\n\nУВАГА: попередній план не пройшов перевірку. Використай його як основу: збережи сцени, що проходять перевірку й розкривають тему, виправ помилки та сам ДОДАЙ відповідні сцени з матеріалу для недоукомплектованих актів. Поверни повний список із 14–22 різних сцен, рівно 1 hook і щонайменше 3 сцени кожної ролі form, psychology, philosophy та catharsis; не дублюй сцени. Перевір повне есе на 4–8 хвилин. Скороти reasoning до 300 символів і поверни ТІЛЬКИ валідний JSON без markdown."

    /// Системная инструкция этапа 1: пять тем-кандидатов и больше ничего.
    static func candidatesInstructions(movieTitle: String) -> String {
        """
        Ти — редактор українського кіноесе за фільмом «\(movieTitle)».
        За наведеними діалогами визнач П'ЯТЬ РІЗНИХ тем, від найточнішої до слабших.
        Головна тема має називати центральний конфлікт: чого прагне герой,
        який вибір робить і чим за нього платить. Це аргумент есе, не переказ сюжету.
        word — одне звичайне українське слово, іменник у називному відмінку,
        ВЕЛИКИМИ літерами; називний відмінок; щонайменше 4 літери, не більше 18. Без новотворів, описок, займенників
        і прихованих метафор. Слово не мусить дослівно звучати в діалогах.
        Ми НЕ даємо тобі списку тем: визнач їх із матеріалу.
        Не прив'язуй різні теми до одного префікса чи звучання.
        Глядач має зрозуміти предмет розмови зі слова й назви, без переозначення.
        why — конкретний причинний ланцюжок: проблема → рішення → наслідок.
        title — ясна природна назва YouTube, що відповідає цьому аргументу.
        Перевір українську граматику. Можеш повторювати потрібні слова з матеріалу.
        evidenceTimecodes — три реальні секунди з наведених діалогів у різних
        частинах історії, які підтверджують тему. Не вигадуй відсутніх сцен.

        Поверни СУВОРО один валідний JSON-об'єкт, без markdown і без тексту до чи після нього:
        {"candidates":[
          {"word":"<СЛОВО_ТЕМИ>",
           "tagline":"<СЛОГАН ДО 12 СЛІВ>",
           "why":"<ДО 25 СЛІВ: чому саме це слово є прихованим двигуном сюжету>",
           "title":"<ЗАГОЛОВОК YouTube ДО 60 СИМВОЛІВ>",
           "evidenceTimecodes":[0.0, 0.0, 0.0]}
        ]}
        П'ять об'єктів, п'ять РІЗНИХ слів і п'ять різних граней фільму.
        evidenceTimecodes — три таймкоди, де діалоги доводять конфлікт цієї теми; самої згадки слова недостатньо.
        Зразок вище — приклад ФОРМАТУ, а НЕ змісту: ні слова, ні таймкоди з нього брати не можна.
        """
    }

    /// Пользовательский промпт этапа 1: заголовок, синопсис и укороченный дайджест.
    static func candidatesPrompt(movieTitle: String, overview: String, digest: String) -> String {
        var parts: [String] = ["Фільм: «\(movieTitle)»"]
        if !overview.isEmpty {
            parts.append("Синопсис/сюжет фільму:\n\"\"\"\n\(overview)\n\"\"\"")
        }
        parts.append("""
            Зріз діалогів фільму (хронологічно, таймкоди — секунди від початку фільму, наприклад [754.5] означає 12 хвилин 34.5 секунди):
            \"\"\"
            \(digest)
            \"\"\"
            Дай П'ЯТЬ тем-кандидатів у форматі системної інструкції. Тільки JSON.
            """)
        return parts.joined(separator: "\n\n")
    }

    /// Довжина рамки промпта этапа 1 без дайджеста, але з ремаркою повтору: це той
    /// самий зібраний рядок, що піде в модель, тому міряємо його, а не константу.
    static func candidatesFrameChars(movieTitle: String, overview: String) -> Int {
        candidatesPrompt(movieTitle: movieTitle, overview: overview, digest: "").count
            + candidatesRetryNote.count + 320
    }

    /// Добавка к системной инструкции этапа 2: темы уже найдены и отобраны
    /// гейтом, поэтому альтернативные грани модель больше не просим.
    static func stage2Focus(winner: String, runnersUp: [String]) -> String {
        var lines: [String] = [
            "ЕТАП 2. Теми-кандидати вже знайдені попереднім проходом і перевірені:",
            "ГОЛОВНА ТЕМА ЦЬОГО ЕСЕ: «\(winner)» — тримайся її, все есе будуєш навколо неї."
        ]
        if !runnersUp.isEmpty {
            lines.append("Інші перевірені кандидати (НЕ повторюй їх, НЕ пропонуй нових): \(runnersUp.joined(separator: ", ")).")
        }
        lines.append("Поле alternativeConcepts НЕ заповнюй: поверни порожній масив — грані вже обрані раніше.")
        lines.append("Ключі JSON пиши в порядку: primaryConcept → essayPlan → selectedMoments → reasoning.")
        return lines.joined(separator: "\n")
    }

    /// Пользовательский промпт этапа 2. Собрание вынесено сюда вместе с этапом 1:
    /// бюджет KV міряється цими самими рядками, тому другої копії рамки існувати не
    /// повинно — саме через неї «недолічені» ~3 800 токенів інструкцій виштовхнули
    /// промпт за стелю KV.
    static func essayPrompt(
        movieTitle: String,
        overview: String,
        theme: String,
        tagline: String,
        digest: String
    ) -> String {
        var parts: [String] = ["Фільм: «\(movieTitle)»"]
        if !overview.isEmpty {
            parts.append("Синопсис/сюжет фільму:\n\"\"\"\n\(overview)\n\"\"\"")
        }
        // Критически важно: явно объясняем модели формат таймкодов.
        // Без этой инструкции LLM интерпретирует `[754.5]` как абстрактное число
        // и выдаёт моменты кластерами в первых ~130 секундах вместо распределения
        // по всему фильму (проблема: 10 моментов ~1 с каждый в первые 132 с фильма 9700 с).
        parts.append("Зріз ключових діалогів фільму (хронологічно по всьому сюжету, таймкоди — секунди від початку фільму, наприклад [754.5] означає 12 хвилин 34.5 секунди):\n\"\"\"\n\(digest)\n\"\"\"")
        parts.append("""
            Тема цього есе: «\(theme)» — \(tagline)
            Зроби ЕСЕ НА ЦЮ ТЕМУ: обґрунтуй вибір (aiReasoning), склади план (essayPlan) і збери пул сцен.
            Склади план есе (essayPlan): thesis, один hook, 2 ctaVariants, actFocus для form/psychology/philosophy/catharsis.
            ВИЗНАЧ 14–22 КОНКРЕТНІ СЦЕНИ для монтажу (selectedMoments) з точними таймкодами.
            Побудуй завершений план із п'яти актів: рівно одна сцена hook і щонайменше три
            сцени для кожного з form, psychology, philosophy та catharsis. У кожного моменту
            має бути одна чітка роль; сцени кожного акта разом доводять його actFocus, а всі
            акти послідовно доводять thesis. Кожен момент — цілісна сцена 18–40 с.
            Сам перевір, що сумарна тривалість з монтажними паузами вкладається у 4–8 хвилин.
            Це готовий монтажний план, а не запас: застосунок не додаватиме, не прибиратиме,
            не обрізатиме і не переноситиме сцени між актами.
            Кожному моменту признач actRole (hook|form|psychology|philosophy|catharsis), supports і featured.
            evidenceQuote — коротка ДОСЛІВНА цитата (3–8 слів) із діалогу ВСЕРЕДИНІ startTime/endTime.
            Цитата з іншої частини фільму не підтверджує таймкод. Перевір кожну сцену за матеріалом,
            а supports пояснює, як саме ця сцена доводить тезу свого акта, без загальних компліментів.
            Розподіляй сцени за РОЛЛЮ В ІСТОРІЇ, а не рівномірно по хронометражу: хук може бути з будь-якої частини фільму.
            ТАЙМКОДИ — секунди від початку фільму: якщо дія біля діалогу [754.5], то startTime ≈ 754.5.
            alternativeConcepts залиш порожнім — грані теми знайдені попереднім етапом.
            Поверни СУВОРО валідний JSON-об'єкт у форматі системної інструкції.
            """)
        return parts.joined(separator: "\n\n")
    }

    /// Рамка промпта этапа 2 без дайджеста і з ремаркою повтору — найгірший захід.
    static func essayFrameChars(
        movieTitle: String,
        overview: String,
        theme: String,
        tagline: String
    ) -> Int {
        essayPrompt(
            movieTitle: movieTitle, overview: overview, theme: theme, tagline: tagline, digest: "").count
            + essayRetryNote.count
            + evidenceFeedbackChars + essaySceneContextChars + 60
    }
}
